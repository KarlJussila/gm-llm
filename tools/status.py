#!/usr/bin/env python3
"""
Emit every live number the planning docs quote, into HANDOFF.md's generated block.

The rule this exists to enforce (handoff-rounds § Numbers): HANDOFF.md is *rewritten*
every round, and a session rewriting a doc reconstructs its numbers from context instead
of re-running the command. So a count lives in a ratchet, in this generated block, or
nowhere — never typed into prose.

Everything here is derived from the repo, deliberately. Bench batch state (how many runs
are complete / capped / reconcile-pending) is *not* here: `bench-out/` is gitignored and
machine-local, so it would make `--check` fail differently on every clone. That query
belongs in the bench CLI — see ROADMAP track "bench ergonomics".

    python3 tools/status.py            # print the block
    python3 tools/status.py --write    # rewrite it into HANDOFF.md
    python3 tools/status.py --check    # non-zero if HANDOFF.md's block is stale (the gate)
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
HANDOFF = ROOT / "HANDOFF.md"
BEGIN = "<!-- status:begin — generated by tools/status.py, do not edit -->"
END = "<!-- status:end -->"

# The model-facing prose corpus, by loading bucket. These are the three homes named in
# CLAUDE.md § The prompts, and the totals are what the /refine-prompts workstream moves.
CORPUS = [
    ("agents", "gm_llm/assets/opencode/agent/*.md"),
    ("skills", "gm_llm/assets/opencode/skills/*/SKILL.md"),
    ("briefs", "gm_llm/orchestrator/prompts/*.md"),
]


def _lines(path: pathlib.Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def _version() -> str:
    text = (ROOT / "gm_llm" / "__init__.py").read_text(encoding="utf-8")
    m = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']', text, re.M)
    return m.group(1) if m else "?"


def _corpus() -> tuple[list[str], int]:
    parts, total = [], 0
    for label, pat in CORPUS:
        files = sorted(ROOT.glob(pat))
        n = sum(_lines(f) for f in files)
        total += n
        parts.append(f"{label} **{len(files)}** files / **{n}** lines")
    return parts, total


def _fixture() -> str:
    """The bench fixture's shape — what `bench run` plays against by default. Sessions are
    flat files (`session-N.md`, `-plan`, `-notes`, `-transcript`), not directories, so count
    distinct N and report which are *played* (a transcript exists) versus merely planned:
    bench plays the first unplayed session, so that split is the fixture's actual shape."""
    fx = ROOT / "dev" / "fixtures" / "hollowfell"
    sessions = fx / "campaign" / "sessions"
    if not sessions.is_dir():
        return "**absent**"
    played, planned = set(), set()
    for f in sessions.glob("session-*.md"):
        m = re.match(r"session-(\d+)", f.name)
        if not m:
            continue
        (played if f.name.endswith("-transcript.md") else planned).add(int(m.group(1)))
    nxt = min(planned - played, default=None)
    tail = f"plays session **{nxt}**" if nxt else "nothing left to play"
    return (f"`{fx.relative_to(ROOT)}` — **{len(played)}** played, "
            f"**{len(planned | played)}** planned; {tail}")


def block() -> str:
    parts, total = _corpus()
    return "\n".join([
        BEGIN,
        "",
        "| | |",
        "|---|---|",
        f"| **Version** | **{_version()}** (`gm_llm/__init__.py` — the only home) |",
        f"| **Prompt corpus** | {' · '.join(parts)} · **{total}** lines total |",
        f"| **Bench fixture** | {_fixture()} |",
        "",
        END,
    ])


def _splice(text: str, new: str) -> str:
    i, j = text.find(BEGIN), text.find(END)
    if i == -1 or j == -1:
        sys.exit("status.py: HANDOFF.md is missing the status:begin/status:end markers")
    return text[:i] + new + text[j + len(END):]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="rewrite HANDOFF.md's block")
    ap.add_argument("--check", action="store_true", help="fail if the block is stale")
    args = ap.parse_args()

    new = block()
    if not (args.write or args.check):
        print(new)
        return 0

    text = HANDOFF.read_text(encoding="utf-8")
    updated = _splice(text, new)
    if args.check:
        if updated != text:
            print("status.py --check: HANDOFF.md's numbers are stale — "
                  "run `python3 tools/status.py --write`", file=sys.stderr)
            return 1
        print("status.py --check: HANDOFF.md's numbers are current")
        return 0
    if updated != text:
        HANDOFF.write_text(updated, encoding="utf-8")
        print("status.py: rewrote HANDOFF.md's numbers block")
    else:
        print("status.py: HANDOFF.md's numbers were already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
